/** Exit codes: 0 ok, 1 verification/command failure, 2 usage error. */
const OK = 0;
const FAILED = 1;
const USAGE = 2;

class UsageError extends Error {}

const USAGE_TEXT =
  'usage: cli <create|advance|inspect|verify|replay|golden|package-b-golden|package-c-golden|package-d-golden|package-e-golden> [--file <career.json>] ' +
  '[--world-id <id>] [--days <n>] [--repair] [--write]';

interface Parsed {
  readonly command: string;
  readonly options: ReadonlyMap<string, string | true>;
}

const parseArgs = (argv: readonly string[]): Parsed => {
  const [command, ...rest] = argv;
  if (command === undefined) throw new UsageError('missing command');
  const options = new Map<string, string | true>();
  for (let i = 0; i < rest.length; i++) {
    const token = rest[i] as string;
    if (!token.startsWith('--'))
      throw new UsageError(`unexpected argument "${token}"`);
    const key = token.slice(2);
    const next = rest[i + 1];
    if (next !== undefined && !next.startsWith('--')) {
      options.set(key, next);
      i += 1;
    } else {
      options.set(key, true);
    }
  }
  return { command, options };
};

const requireString = (p: Parsed, key: string): string => {
  const v = p.options.get(key);
  if (typeof v !== 'string')
    throw new UsageError(`--${key} <value> is required`);
  return v;
};

/** A view of a store that can be read but never changed (verify/inspect must not write). */
const readOnly = (store: CareerStore): CareerStore => ({
  initialize: () => store.initialize(),
  saveCommit: () => Promise.reject(new Error('read-only store')),
  loadLatest: () => store.loadLatest(),
  listVerifiedSnapshots: () => store.listVerifiedSnapshots(),
  loadHistorySince: (r) => store.loadHistorySince(r),
  markRecovery: () => Promise.resolve(),
  loadRecoveryLog: () => store.loadRecoveryLog(),
});

const viewOf = (kernel: WorldKernel) => ({
  worldId: kernel.world.worldId,
  simDate: kernel.world.simDate,
  revision: Number(kernel.world.revision),
  eventCount: kernel.eventCount,
  rngDraws: kernel.world.rng.draws,
  fingerprint: fingerprintWorld(kernel.world),
  eventChainHead: kernel.chainHead,
});

