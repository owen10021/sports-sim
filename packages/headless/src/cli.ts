export const runCli = async (
  argv: readonly string[],
  io: CliIo,
): Promise<number> => {
  try {
    const parsed = parseArgs(argv);
    switch (parsed.command) {
      case 'create':
        return await create(parsed, io);
      case 'advance':
        return await advance(parsed, io);
      case 'inspect':
        return await inspect(parsed, io);
      case 'verify':
        return await verify(parsed, io);
      case 'replay':
        return await replay(parsed, io);
      case 'golden':
        return golden(parsed, io);
      case 'package-b-golden':
        return packageBGolden(parsed, io);
      case 'package-c-golden':
        return packageCGolden(parsed, io);
      case 'package-d-golden':
        return packageDGolden(parsed, io);
      case 'package-e-golden':
        return packageEGolden(parsed, io);
      default:
        throw new UsageError(`unknown command "${parsed.command}"`);
    }
  } catch (error) {
    if (error instanceof UsageError) {
      io.err(`${error.message}\n${USAGE_TEXT}`);
      return USAGE;
    }
    io.err(
      error instanceof Error
        ? `${error.name}: ${error.message}`
        : String(error),
    );
    return FAILED;
  }
};

const openStore = async (file: string): Promise<JsonFileCareerStore> => {
  const store = new JsonFileCareerStore(file);
  await store.initialize();
  return store;
};

const loadOptions = { ruleset: SYNTHETIC_RULESET, seed: SYNTHETIC_SEED };

const create = async (p: Parsed, io: CliIo): Promise<number> => {
  const file = requireString(p, 'file');
  const store = await openStore(file);
  if ((await store.loadLatest()) !== null) {
    io.err(`A career already exists in ${file}; refusing to overwrite it`);
    return FAILED;
  }
  const idOption = p.options.get('world-id');
  const id = typeof idOption === 'string' ? idOption : `world-${randomUUID()}`;
  const world = createWorld(SYNTHETIC_SEED, SYNTHETIC_RULESET, {
    newWorldId: () => worldId(id),
  });
  const kernel = WorldKernel.fromGenesis(world, SYNTHETIC_RULESET);
  await store.saveCommit({
    snapshot: sealSnapshot({
      world: kernel.world,
      chainHead: kernel.chainHead,
      eventCount: 0,
      knownCommandIds: [],
    }),
    commands: [],
    events: [],
  });
  io.out(JSON.stringify(viewOf(kernel)));
  return OK;
};

const requireLoaded = async (store: CareerStore, io: CliIo) => {
  const outcome = await loadCareer(store, loadOptions);
  if (outcome.status === 'loaded') return outcome;
  const reasons = 'report' in outcome ? outcome.report.reasons : [];
  io.err(`career is not loadable (${outcome.status}): ${reasons.join('; ')}`);
  return null;
};

const advance = async (p: Parsed, io: CliIo): Promise<number> => {
  const file = requireString(p, 'file');
  const days = Number(requireString(p, 'days'));
  if (!Number.isInteger(days))
    throw new UsageError('--days must be an integer');
  if (!existsSync(file)) {
    io.err(`${file} does not exist; run create first`);
    return FAILED;
  }
  const store = await openStore(file);
  const loaded = await requireLoaded(readOnly(store), io);
  if (loaded === null) return FAILED;
  const kernel = loaded.kernel;
  const envelope = {
    commandId: commandId(
      `cmd-${String(kernel.knownCommandIds.length + 1).padStart(6, '0')}`,
    ),
    expectedRevision: worldRevision(Number(kernel.world.revision)),
    actor: { kind: 'test_harness', id: entityId('headless-cli') },
    command: { type: 'AdvanceDays', days },
  } as unknown as CommandEnvelope;
  const result = kernel.execute(envelope);
  if (!result.ok) {
    io.err(`REJECTED ${result.rejection.code}: ${result.rejection.message}`);
    return FAILED;
  }
  await store.saveCommit({
    snapshot: sealSnapshot({
      world: kernel.world,
      chainHead: kernel.chainHead,
      eventCount: kernel.eventCount,
      knownCommandIds: kernel.knownCommandIds,
    }),
    commands: [{ envelope, resultRevision: Number(result.world.revision) }],
    events: result.events,
  });
  io.out(JSON.stringify(viewOf(kernel)));
  return OK;
};

const inspect = async (p: Parsed, io: CliIo): Promise<number> => {
  const file = requireString(p, 'file');
  if (!existsSync(file)) {
    io.err(`${file} does not exist`);
    return FAILED;
  }
  const store = readOnly(await openStore(file));
  const loaded = await requireLoaded(store, io);
  if (loaded === null) return FAILED;
  io.out(
    JSON.stringify({
      ...viewOf(loaded.kernel),
      snapshotRevision: loaded.snapshot.revision,
    }),
  );
  return OK;
};

const verify = async (p: Parsed, io: CliIo): Promise<number> => {
  const file = requireString(p, 'file');
  if (!existsSync(file)) {
    io.err(`${file} does not exist`);
    return FAILED;
  }
  const store = readOnly(await openStore(file));
  const outcome = await loadCareer(store, loadOptions);
  const replay = await verifyCareerReplay(store, SYNTHETIC_RULESET);
  const reasons = [
    ...('report' in outcome ? outcome.report.reasons : []),
    ...replay.reasons,
  ];
  const ok = outcome.status === 'loaded' && replay.ok;
  io.out(
    JSON.stringify({
      ok,
      status: outcome.status,
      replayOk: replay.ok,
      reasons,
    }),
  );
  return ok ? OK : FAILED;
};

const replay = async (p: Parsed, io: CliIo): Promise<number> => {
  const file = requireString(p, 'file');
  if (!existsSync(file)) {
    io.err(`${file} does not exist`);
    return FAILED;
  }
  const store = await openStore(file);
  const check = await verifyCareerReplay(readOnly(store), SYNTHETIC_RULESET);
  if (p.options.get('repair') !== true) {
    io.out(
      JSON.stringify({
        ok: check.ok,
        reasons: check.reasons,
        fingerprint: check.fingerprint,
        chainHead: check.chainHead,
      }),
    );
    return check.ok ? OK : FAILED;
  }
  if (check.ok) {
    io.out(
      JSON.stringify({
        ok: true,
        repaired: false,
        note: 'stored state already matches replay; nothing to repair',
      }),
    );
    return OK;
  }
  const repair = await repairLatestFromHistory(store, {
    ...loadOptions,
    reasons: check.reasons,
  });
  if (repair.status === 'repaired') {
    io.out(JSON.stringify({ ok: true, repaired: true, report: repair.report }));
    return OK;
  }
  io.out(
    JSON.stringify({ ok: false, repaired: false, reasons: repair.reasons }),
  );
  return FAILED;
};

const golden = (p: Parsed, io: CliIo): number => {
  const result = runGoldenScenario();
  if (p.options.get('write') === true) {
    // One immutable fixture per scenario id: the world-model-1 file is never overwritten.
    const fixture = join(
      repoRoot,
      'fixtures',
      'golden',
      `${result.scenario}.json`,
    );
    mkdirSync(dirname(fixture), { recursive: true });
    writeFileSync(fixture, `${JSON.stringify(result, null, 2)}\n`, 'utf8');
    writeFileSync(
      join(repoRoot, 'packages', 'sim-core', 'src', 'goldenExpected.ts'),
      renderGoldenExpected(result),
      'utf8',
    );
    io.out(
      JSON.stringify({
        written: true,
        fingerprint: result.fingerprint,
        eventChainHead: result.eventChainHead,
      }),
    );
    return OK;
  }
  const diffs = diffGolden(result, GOLDEN_EXPECTED);
  io.out(
    JSON.stringify({
      match: diffs.length === 0,
      diffs,
      fingerprint: result.fingerprint,
      eventChainHead: result.eventChainHead,
      finalSimDate: result.finalSimDate,
      revision: result.revision,
      eventCount: result.eventCount,
      commandDays: result.commandDays,
    }),
  );
  return diffs.length === 0 ? OK : FAILED;
};

